/* ============================================================
   Googleスプレッドシート連携の設定
   ------------------------------------------------------------
   1. Googleスプレッドシートで入出金明細用のシートを用意する。
      列名・列数は下の2パターンどちらでもよい（列の順番は自由）。

      【パターンA】自分で「金額」列（符号つき）を1本にまとめる場合:
        日付 | 内容 | カテゴリ | 金額 | 残高
        2026/09/01 | 給与振込 | 給与 | 300000 | 5633052
        2026/09/03 | コンビニ | その他 | -1200  | 5631852

      【パターンB】銀行からダウンロードしたCSVをそのまま使う場合
      （多くの銀行がこの「出金金額」「入金金額」を分けた形式で出力する）:
        日付 | 内容 | 出金金額(円) | 入金金額(円) | 残高(円)
        2026/07/29 | ＡＴＭ　○○銀行 | 30,000 |        | 893,759
        2026/07/24 | 振込＊○○      |        | 318,224 | 1,724,709

        この形式には「カテゴリ」列が無くてもよい。内容（内容列の文字列）から
        ATM／口座振替／給与／振込／利息／税金／普通 などのキーワードを見て
        自動でアイコンを推測するので、パターンBの銀行CSVはそのままインポート
        するだけで使える。数字はカンマ区切り「30,000」のままで問題ない。

      共通の注意点:
      ・日付: 2026/09/01 でも 2026-09-01 でもどちらでも読み込める。
      ・残高: その取引が終わった後の残高。分かる分だけ埋めればよく、
        空欄の行は前後の行から自動的に補完される。
        1行も残高が無い場合は、shared-data.js の残高から逆算する。
      ・カテゴリ（パターンAで使う場合）: 次のいずれかを入力する。
          ATM ／ 口座振替 ／ 振込入金 ／ 振込出金 ／ 口座間 ／ 給与 ／ 税金 ／ 利息 ／ その他
      ・「メモ」など上記に無い列があっても、単に無視されるだけなので問題ない。

   2. スプレッドシートを「ウェブに公開」する。
      Googleスプレッドシート上部メニュー →
      ファイル → 共有 → ウェブに公開 →
      対象シートを選択し、形式を「カンマ区切りの値(.csv)」にして公開。
      発行されたURL（.../pub?...&output=csv という形）を下の csvUrl に貼り付ける。

   3. 貼り付けるだけで balance.html / transactions.html が
      自動的にこのシートの内容を読みに行くようになる（グラフ・明細一覧・
      現在残高のすべてがこのシートのデータに切り替わる）。
      csvUrl が空のままの間は、これまで通りサンプルデータが使われる。
   ============================================================ */

